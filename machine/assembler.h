bool rex_w(BYTE rex,bool strict=false) {
	if (strict && (rex>>4)!=4) return false;
	return (rex>>3)&1;
}

bool rex_r(BYTE rex,bool strict=false) {
	if (strict && (rex>>4)!=4) return false;
	return (rex>>2)&1;
}

bool rex_x(BYTE rex,bool strict=false) {
	if (strict && (rex>>4)!=4) return false;
	return (rex>>1)&1;
}

bool rex_b(BYTE rex,bool strict=false) {
	if (strict && (rex>>4)!=4) return false;
	return rex&1;
}

